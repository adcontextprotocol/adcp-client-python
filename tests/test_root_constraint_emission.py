"""Generation aborts on a constraint keyword the grammar cannot compile.

This is the class-level guarantee, exercised rather than assumed. After the
constraint reader became key-consuming there are two channels to a model weaker
than its schema, and they differ in kind. A keyword kind the grammar does not
know cannot produce a weaker model BECAUSE IT CANNOT PRODUCE A MODEL:
generation raises, and ``scripts/generate_types.py`` generates into a staging
tree and installs only on success, so nothing ships. A semantic slip inside a
kind the grammar does know is a different, named residual, bounded to the
vocabulary primitives and witnessed by the differential parity suite.

So the test below is not "a bad document is refused". It is: the attempt to
generate a model from a schema this SDK cannot express FAILS, and names the
file, the JSON pointer and the keyword a maintainer has to act on.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from scripts import post_generate_fixes as fixes
from scripts.schema_constraints import UnexpressibleKeywordError

#: A generated module shaped like the ones the pass edits: one flat class over
#: the root's properties, on the hand-written base that declares no fields.
_MODULE = """# generated by datamodel-codegen:
#   filename:  thing.json

from __future__ import annotations

from adcp.types.base import AdCPBaseModel


class Thing(AdCPBaseModel):
    a: str | None = None
    b: str | None = None
"""

_SCHEMA: dict[str, object] = {
    "title": "Thing",
    "type": "object",
    "properties": {"a": {"type": "string"}, "b": {"type": "string"}},
    "anyOf": [{"required": ["a"]}, {"required": ["b"]}],
}


@pytest.fixture
def staged(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> tuple[Path, Path]:
    """A one-schema bundle and the one module generated from it."""
    schemas = tmp_path / "schemas"
    output = tmp_path / "domains"
    schemas.mkdir()
    output.mkdir()
    (output / "thing.py").write_text(_MODULE)
    monkeypatch.setattr(fixes, "SCHEMA_DIR", schemas)
    monkeypatch.setattr(fixes, "OUTPUT_DIR", output)
    return schemas, output


def test_a_compilable_root_gets_its_validator(staged: tuple[Path, Path]) -> None:
    """The green path, so the red one below is not red for a setup reason."""
    schemas, output = staged
    (schemas / "thing.json").write_text(json.dumps(_SCHEMA))

    fixes.enforce_root_constraints()

    emitted = (output / "thing.py").read_text()
    assert f"def {fixes.ROOT_CONSTRAINT_VALIDATOR}" in emitted
    # ``sent`` rather than ``supplied``: the fixture declares ``a`` as a plain
    # ``string``, so the schema forbids null there and the client drops a
    # null-valued key on the way out.
    assert "_c.sent(self, 'a')" in emitted
    assert "at least one of these field groups" in emitted


def test_a_keyword_the_grammar_cannot_compile_aborts_generation(
    staged: tuple[Path, Path],
) -> None:
    """No model ships, and the refusal names what a maintainer must act on.

    ``unevaluatedProperties`` is a real 2019-09 keyword with real validation
    semantics and no production in the grammar, which is exactly the shape of
    the hazard: a future bundle adding a keyword kind this SDK cannot express.
    """
    schemas, output = staged
    before = (output / "thing.py").read_text()
    (schemas / "thing.json").write_text(
        json.dumps(
            {
                **_SCHEMA,
                "anyOf": [
                    {"required": ["a"], "unevaluatedProperties": False},
                    {"required": ["b"]},
                ],
            }
        )
    )

    with pytest.raises(UnexpressibleKeywordError) as raised:
        fixes.enforce_root_constraints()

    assert raised.value.schema_file == "thing.json"
    assert raised.value.pointer == "anyOf/0"
    assert raised.value.keyword == "unevaluatedProperties"
    assert (
        output / "thing.py"
    ).read_text() == before, (
        "the module was edited before the refusal, so a weaker model could ship"
    )


def test_the_abort_is_not_caught_between_the_pass_and_the_install() -> None:
    """A skip lane would have to exist somewhere; this is where it would be.

    ``post_generate_fixes.main`` calls each fix in a bare loop, so a refusal
    becomes that process's non-zero exit. ``generate_types.py`` runs it as a
    subprocess, checks the return code, and installs the staged tree only
    afterwards -- so a refusal stops generation with the previous tree in place.
    Asserted on the source because what is being asserted is the ABSENCE of a
    handler and the ORDER of two statements, and the alternative is a
    ten-minute regeneration per assertion.
    """
    import ast
    import inspect

    loop = ast.parse(inspect.getsource(fixes.main))
    assert not [node for node in ast.walk(loop) if isinstance(node, ast.Try)], (
        "post_generate_fixes.main wraps the fix pipeline in a try, which is where "
        "a refusal would become a skip"
    )

    generating = inspect.getsource(_generate_module().main)
    checked = generating.index("result.returncode != 0")
    installed = generating.index("_install_generated_artifacts(")
    assert checked < installed, (
        "generate_types installs the staged tree before checking whether the "
        "post-generation pass refused"
    )


def _generate_module() -> object:
    from scripts import generate_types

    return generate_types
