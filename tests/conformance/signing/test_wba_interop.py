def _rsa_jwk(public: rsa.RSAPublicKey) -> dict[str, str]:
    from adcp.signing.crypto import b64url_encode

    numbers = public.public_numbers()
    return {
        "kty": "RSA",
        "n": b64url_encode(numbers.n.to_bytes((numbers.n.bit_length() + 7) // 8, "big")),
        "e": b64url_encode(numbers.e.to_bytes((numbers.e.bit_length() + 7) // 8, "big")),
    }


def test_rsa_pss_appendix_e_vector():
    public = serialization.load_pem_public_key(RFC9421_TEST_KEY_RSA_PSS)
    assert isinstance(public, rsa.RSAPublicKey)
    jwk = _rsa_jwk(public)
    assert thumbprint_key_id(jwk) == "oD0HwocPBSfpNy5W3bpJeyFGY_IQ_YpqxSjQ3Yd-CLA"
    assert _algorithm(jwk) == ALG_RSA_PSS_SHA512
    assert is_64_byte_nonce(APPENDIX_E_NONCE), "padded standard base64 of 64 bytes"
    headers = {
        "signature-agent": 'agent2="https://signature-agent.test"',
        "signature-input": APPENDIX_E_INPUT,
        "signature": APPENDIX_E_SIGNATURE,
    }
    base = _signature_base("sig2", "GET", "https://example.com/", headers)
    assert base.decode() == (
        '"@authority": example.com\n'
        '"signature-agent";key="agent2": "https://signature-agent.test"\n'
        f'"@signature-params": {APPENDIX_E_INPUT.removeprefix("sig2=")}'
    )
    _components, params = parse_dictionary(APPENDIX_E_INPUT)["sig2"]
    signature = parse_dictionary(APPENDIX_E_SIGNATURE)["sig2"]
    message = Request("GET", "https://example.com/", headers)
    assert (
        _verify_crypto(message, label="sig2", params=params, signature=signature, jwk=jwk)
        == ALG_RSA_PSS_SHA512
    )
    tampered = Request("GET", "https://example.net/", headers)
    with pytest.raises(WbaVerificationError, match="did not verify"):
        _verify_crypto(tampered, label="sig2", params=params, signature=signature, jwk=jwk)


async def test_rsa_pss_identity_round_trip_and_key_bounds():
    private = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    origin = "https://buyer.example.com"
    directory = sign_key_directory(agent_origin=origin, private_keys=[private], created=1000)
    assert 'alg="rsa-pss-sha512"' in directory.headers["Signature-Input"]
    body = b'{"jsonrpc":"2.0","id":1,"method":"tools/list"}'
    headers = {"content-type": "application/json"}
    headers.update(
        sign_wba_request(
            method="POST",
            url="https://seller.example.com/mcp",
            headers=headers,
            body=body,
            private_key=private,
            agent_origin=origin,
            created=1000,
        )
    )

    async def fetch(url, *, allow_private=False):
        return directory

    (signer,) = await verify_wba_request(
        method="POST",
        url="https://seller.example.com/mcp",
        headers=headers,
        body=body,
        signer_keys=DiscoveredSignerKeys(fetcher=fetch, clock=lambda: 1001),
        replay_store=InMemoryReplayStore(),
        now=1001,
    )
    assert signer.alg == ALG_RSA_PSS_SHA512
    small = rsa.generate_private_key(public_exponent=65537, key_size=1024)
    with pytest.raises(ValueError, match="2048"):
        public_directory_key(small)
    with pytest.raises(WbaVerificationError):
        _algorithm(_rsa_jwk(small.public_key()))
    with pytest.raises(WbaVerificationError):
        _algorithm({**public_directory_key(private), "e": "AQAA"})  # even exponent
