ROOT = Path(__file__).parents[1] / "vectors" / "wba-interop"
FIXTURES = sorted(path for path in ROOT.glob("*-signed-*.json"))


def test_vendored_fixtures_match_recorded_provenance():
    upstream = json.loads((ROOT / "UPSTREAM.json").read_text())
    vendored = {path.name for path in ROOT.glob("*.json")} - {"UPSTREAM.json"}
    assert vendored == set(upstream["sha256"])
    for name, digest in upstream["sha256"].items():
        assert hashlib.sha256((ROOT / name).read_bytes()).hexdigest() == digest
    assert {path.name.split("-signed-")[0] for path in FIXTURES} == {"adcp-client", "cloudflare"}


def _directory(fixture):
    raw = fixture["directory"]
    return DirectoryResponse(
        body=raw["body"].encode(), headers=dict(raw["headers"]), status=raw["status"]
    )


@pytest.mark.parametrize("path", FIXTURES, ids=lambda path: path.stem)
async def test_python_verifies_foreign_signed_requests(path):
    fixture = json.loads(path.read_text())
    request, expected = fixture["request"], fixture["expected"]
    now = fixture["reference_now"]
    directory_url = fixture["directory"]["url"]

    async def fetch(url, *, allow_private=False):
        assert url == directory_url
        return _directory(fixture)

    (signer,) = await verify_wba_request(
        method=request["method"],
        url=request["url"],
        headers=request["headers"],
        body=request["body"].encode(),
        signer_keys=DiscoveredSignerKeys(fetcher=fetch, clock=lambda: now),
        replay_store=InMemoryReplayStore(),
        now=now,
    )
    assert expected["verifies"] is True
    assert signer.agent_url == expected["identity"]
    assert signer.key_id == expected["keyid"]
    # @target-uri is the URI as received: %7E stays encoded.
    label = next(iter(parse_dictionary(request["headers"]["signature-input"])))
    base = _signature_base(label, request["method"], request["url"], request["headers"]).decode()
    assert base == expected["signature_base"]


@pytest.mark.parametrize("path", FIXTURES, ids=lambda path: path.stem)
def test_foreign_signed_directories_verify(path):
    fixture = json.loads(path.read_text())
    origin = fixture["directory"]["url"].split("/.well-known/")[0]
    keys = verify_directory_response(origin, _directory(fixture), now=fixture["reference_now"])
    assert fixture["expected"]["keyid"] in keys


def test_cloudflare_padded_base64_nonce_is_64_bytes():
    fixture = json.loads((ROOT / "cloudflare-signed-body-request.json").read_text())
    _components, params = parse_dictionary(fixture["request"]["headers"]["signature-input"])["sig1"]
    nonce = params["nonce"]
    assert nonce.endswith("==") and is_64_byte_nonce(nonce) and valid_wba_nonce(nonce)


@pytest.mark.parametrize("path", ["/mcp", "/a%7Eb/mcp/"])
async def test_python_signed_requests_verify_with_the_target_uri_as_sent(path):
    keys = json.loads((ROOT / "keys.json").read_text())["keys"]
    from adcp.signing.crypto import private_key_from_jwk

    jwk = next(key for key in keys if key["kty"] == "OKP")
    private = private_key_from_jwk({**jwk, **jwk["_private_jwk_for_test_only"]})
    origin = "https://buyer.agency.com"
    url = "https://seller.example.com" + path
    body = b'{"jsonrpc":"2.0","id":1,"method":"tools/call","params":{"name":"get_products"}}'
    headers = {"content-type": "application/json"}
    headers.update(
        sign_wba_request(
            method="POST",
            url=url,
            headers=headers,
            body=body,
            private_key=private,
            agent_origin=origin,
            created=1790841610,
        )
    )
    _components, params = parse_dictionary(headers["Signature-Input"])["sig1"]
    # Default nonce: 64 random bytes, unpadded base64url.
    assert len(params["nonce"]) == 86 and is_64_byte_nonce(params["nonce"])
    base = _signature_base("sig1", "POST", url, headers).decode()
    assert f'"@target-uri": {url}\n' in base
    assert '"@authority": seller.example.com\n' in base
    directory = sign_key_directory(agent_origin=origin, private_keys=[private], created=1790841550)

    async def fetch(url, *, allow_private=False):
        return directory

    (signer,) = await verify_wba_request(
        method="POST",
        url=url,
        headers=headers,
        body=body,
        signer_keys=DiscoveredSignerKeys(fetcher=fetch, clock=lambda: 1790841610),
        replay_store=InMemoryReplayStore(),
        now=1790841610,
    )
    assert signer.agent_url == origin
    # A decoded (canonicalized) target URI is a different signature base.
    if "%7E" in path:
        with pytest.raises(WbaVerificationError, match="did not verify"):
            await verify_wba_request(
                method="POST",
                url=url.replace("%7E", "~"),
                headers=headers,
                body=body,
                signer_keys=DiscoveredSignerKeys(fetcher=fetch, clock=lambda: 1790841610),
                replay_store=InMemoryReplayStore(),
                now=1790841610,
            )


